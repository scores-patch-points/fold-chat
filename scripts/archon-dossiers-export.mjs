// scripts/archon-dossiers-export.mjs — turns docs/archons/dossier/*.json into khora/native/organs/archon-dossiers.js,
// the data AntiStrauss's credit disclosure reads at runtime. Generated: edit the dossier, re-run, never the output.
import fs from "node:fs"; import path from "node:path"; import crypto from "node:crypto";
const DIR = "docs/archons/dossier";
const OUT = "/Users/mlacy/Documents/3.0/khora/native/organs/archon-dossiers.js";
const clip = (s, n) => { s = String(s ?? "").replace(/\s+/g, " ").trim(); return s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s; };
const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".json")).sort();
const rows = {};
let digest = crypto.createHash("sha256");
for (const f of files) {
  const raw = fs.readFileSync(path.join(DIR, f), "utf8"); digest.update(raw);
  const d = JSON.parse(raw);
  const bends = (d.bends || []).map((b) => ({ id: b.id, kind: b.kind, ours: clip(b.ours, 260), theirs: clip(b.theirs, 260) }));
  let disclosure = null;
  if (d.standing === "nomination") disclosure = `"${d.handle}" is our own name for this organ; no author's work is claimed${bends.length ? `. Where it borrows an author's authority anyway: ${bends.slice(0, 2).map((b) => clip(b.ours, 110)).join(" | ")}` : ""}.`;
  else if (d.verdict === "fails") disclosure = `The source does not support this use; credit it as our handle, not as the author's argument. ${bends.slice(0, 2).map((b) => `${b.kind}: ${clip(b.ours, 90)} / theirs: ${clip(b.theirs, 110)}`).join(" | ")}`;
  else if (d.verdict === "partial") disclosure = `By our reading, not the author's own claim. ${bends.slice(0, 2).map((b) => `${b.kind}: ${clip(b.ours, 90)} / theirs: ${clip(b.theirs, 110)}`).join(" | ")}`;
  rows[d.handle] = { standing: d.standing, verdict: d.verdict, creditAsScholarship: d.standing !== "nomination" && d.verdict !== "fails", disclosure, bends, snips: d.snips || [], noBendReason: d.noBendReason ?? null };
}
const body = `// native/organs/archon-dossiers.js — GENERATED by the-fold/scripts/archon-dossiers-export.mjs from docs/archons/dossier/*.json.
// Do not edit. Edit the dossier and re-export. This is AntiStrauss's disclosure data: for each archon, the verdict on whether our use
// matches what the author argued, and every place we bend, narrow or invent beyond them (ours vs theirs). A credit line that leaves these out
// lets a name stand in for an argument it does not make. Dossier digest binds this file to its sources.
export const ARCHON_DOSSIERS_DIGEST = ${JSON.stringify(digest.digest("hex"))};
export const ARCHON_DOSSIERS = Object.freeze(${JSON.stringify(rows, null, 1)});
`;
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.error("archon-dossiers.js is stale against docs/archons/dossier — run: node scripts/archon-dossiers-export.mjs"); process.exit(1); }
  console.log("archon-dossiers.js is current"); process.exit(0);
}
fs.writeFileSync(OUT, body);
console.log(`${Object.keys(rows).length} dossiers → ${OUT} (${(body.length / 1024).toFixed(0)} KB)`);
