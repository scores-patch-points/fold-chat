// Build fold-chat-function-words.js from the khora's POSPrior@1 files (Universal Dependencies gold treebanks).
//   node scripts/build-function-words.mjs --src <a CLEAN checkout of the khora>   (default ../khora; pass a clean clone
//   so only COMMITTED priors are used — an uncommitted prior is not stable, and not ours to build on)
// A form is a FUNCTION WORD when ≥ 50% of its tokens (and ≥ 5 tokens) are closed-class: ADP DET PRON AUX CCONJ SCONJ PART.
// Output is tiny (1–2 KB per language): it says which words are common in a language the tab has never searched in.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const arg = (n, d) => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : d);
const SRC = path.resolve(arg("--src", path.join(HERE, "..", "..", "khora")));
const DIR = path.join(SRC, "native", "priors");
const CLOSED = new Set(["ADP", "DET", "PRON", "AUX", "CCONJ", "SCONJ", "PART"]);
// khora's ISO-639-3 file codes → the two-letter codes fold-chat-lang.js detects (UD preferred; UniMorph has no closed classes)
const CODE = { arb: "ar", cmn: "zh", "cmn-hans": "zh", ell: "el", eng: "en", en: "en", fas: "fa", fin: "fi", fra: "fr", heb: "he", kor: "ko", lat: "la", rus: "ru", spa: "es", tur: "tr", deu: "de", jpn: "ja", por: "pt", ita: "it", nld: "nl", pol: "pl", ukr: "uk", swe: "sv", vie: "vi", ind: "id", hin: "hi", ces: "cs", bul: "bg", cat: "ca", ron: "ro", hrv: "hr", slk: "sk", slv: "sl", srp: "sr", urd: "ur", glg: "gl" };
const out = {}, prov = {};
for (const f of fs.readdirSync(DIR).filter((x) => /^pos-[a-z-]+\.json$/.test(x)).sort()) {
  const code3 = f.replace(/^pos-|\.json$/g, "");
  if (/unimorph/.test(code3)) continue;                 // inflection tables: no closed-class tags
  const lang = CODE[code3]; if (!lang || out[lang]) continue;
  const j = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  const words = [];
  for (const [form, tags] of Object.entries(j.forms || {})) { let c = 0, t = 0; for (const [k, n] of Object.entries(tags)) { t += n; if (CLOSED.has(k)) c += n; } if (t >= 5 && c / t >= 0.5) words.push([form, t]); }
  if (!words.length) continue;
  words.sort((a, b) => b[1] - a[1]);
  out[lang] = words.map((w) => w[0]);
  prov[lang] = { file: f, giver: String(j.provenance?.giver || "").replace(/ — .*$/, ""), tokens: j.provenance?.tokens_read ?? null };
}
const head = `// fold-chat-function-words.js — which words are COMMON (function words) in a language, from a prior with a giver.
// GENERATED by scripts/build-function-words.mjs from the khora's POSPrior@1 files (Universal Dependencies gold treebanks,
// CC BY-SA 4.0): a form is a function word when ≥ 50% of its ≥ 5 tokens are closed-class (ADP DET PRON AUX CCONJ SCONJ PART).
// Only priors COMMITTED in the khora are used. Never edit by hand; regenerate. Languages: ${Object.keys(out).join(" ")}.
`;
fs.writeFileSync(path.join(HERE, "..", "fold-chat-function-words.js"), head + `export const GIVERS = Object.freeze(${JSON.stringify(prov)});\nexport const FUNCTION_WORDS = Object.freeze(${JSON.stringify(out)});\n`);
console.log(Object.entries(out).map(([l, w]) => `${l}:${w.length}`).join(" "), "→ fold-chat-function-words.js", Math.round(fs.statSync(path.join(HERE, "..", "fold-chat-function-words.js")).size / 1024) + "KB");
