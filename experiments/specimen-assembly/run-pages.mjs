// run-pages.mjs — the page criteria exactly as frozen in PAGES.md (PAGES.sha256). One run; every verdict printed.
// Usage: node run-pages.mjs      Writes out/pages-results.json and out/ledger-pages*.jsonl
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { makeOracle, OBLIGATION_IDS } from "./lib/pagecheck.mjs";
import { assemblePage, specimenFile } from "./lib/assemble-page.mjs";
import { statusTree, statusLeaves, TREE } from "./lib/holons.mjs";
import { applyEdits } from "./lib/transform.mjs";
import { sha256 } from "./lib/specimen.mjs";
import { Ledger } from "./lib/solver.mjs";
import { makeGuard, diffMasked } from "./lib/guard.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "out");
fs.mkdirSync(OUT, { recursive: true });
const RERUN = process.argv[2] === "--rerun" ? (process.argv[3] || "T5,T6").split(",") : null;   // re-run named criteria, keep the rest of the earlier run
const prevFile = path.join(OUT, "pages-results.json");
const prev = RERUN ? JSON.parse(fs.readFileSync(prevFile, "utf8")) : null;
if (RERUN) fs.copyFileSync(prevFile, path.join(OUT, `pages-results.before-${new Date().toISOString().replace(/[:.]/g, "-")}.json`));
const res = prev ? { ...prev, rerunAt: new Date().toISOString(), reran: RERUN, criteria: { ...prev.criteria } } : { startedAt: new Date().toISOString(), pagesSha256: sha256(fs.readFileSync(path.join(HERE, "PAGES.md"), "utf8")), prereg: fs.readFileSync(path.join(HERE, "PAGES.sha256"), "utf8").trim().split("\n"), criteria: {} };
res.pagesMatchesPrereg = res.pagesSha256 === res.prereg[0].split(" ")[0];
const ok = (checks, name, pass, detail = "") => { checks.push({ name, ok: pass === null ? null : !!pass, detail }); return pass; };
const verdictOf = (checks) => (checks.some((c) => c.ok === false) ? "FALSIFIED" : checks.some((c) => c.ok === null) ? "NOT EVALUATED (in part)" : "PASS");
const crit = async (id, fn) => {
  if (RERUN && !RERUN.includes(id)) return;
  const t = Date.now(); const checks = []; let evidence = {};
  console.log(`\n== ${id}`);
  try { evidence = (await fn(checks)) || {}; } catch (e) { ok(checks, "ran without throwing", false, e.stack); }
  res.criteria[id] = { verdict: verdictOf(checks), ms: Date.now() - t, checks, evidence };
  console.log(`${id}: ${res.criteria[id].verdict} (${Date.now() - t} ms)`);
  for (const c of checks) console.log(`   ${c.ok === null ? "n/a " : c.ok ? "ok  " : "FAIL"} ${c.name}${c.detail ? " — " + String(c.detail).slice(0, 260) : ""}`);
};

const pagesDir = path.join(HERE, "pages");
const pool = ["tip-suite.html", "bill-splitter.html", "counter.html", "todo.html", "contact-form.html"].map((f) => specimenFile(fs, pagesDir, f));
const oracle = await makeOracle();
const ledgerA = new Ledger(path.join(OUT, "ledger-pages.jsonl"));
const ledgerB = new Ledger(path.join(OUT, "ledger-pages-void.jsonl"));
let A, B, tA;

await crit("T1", async (c) => {
  tA = Date.now();
  A = await assemblePage(pool, oracle, ledgerA, { onState: (s) => process.stdout.write(`\r   cut ${s.step}: ${s.bytes} B  ${s.note.slice(0, 50).padEnd(50)}`) });
  console.log();
  const row = (n) => A.rows.find((r) => r.name === n);
  ok(c, "tip-suite holds 11/11", row("tip-suite").passed === 11, `${row("tip-suite").passed}/11`);
  ok(c, "every other specimen fails at least one", A.rows.filter((r) => r.name !== "tip-suite").every((r) => r.passed < 11), A.rows.map((r) => `${r.name} ${r.passed}`).join(", "));
  const held = statusLeaves(statusTree(row("bill-splitter").results)).filter((l) => l.status === "held").map((l) => l.id).sort();
  ok(c, "bill-splitter holds exactly bill-input, people-input, guard, shell", JSON.stringify(held) === JSON.stringify(["bill-input", "guard", "people-input", "shell"]), held.join(", "));
  return { rows: A.rows.map((r) => ({ name: r.name, bytes: r.bytes, passed: r.passed, results: r.results })) };
});

await crit("T2", async (c) => {
  ok(c, "assembled", A.status === "assembled", A.status);
  const input = pool.find((p) => p.name === A.chosen.name).html;
  ok(c, "chosen the superset", A.chosen.name === "tip-suite");
  ok(c, "all 11 obligations hold on the result, in Chromium", OBLIGATION_IDS.every((id) => A.final[id].pass), OBLIGATION_IDS.filter((id) => !A.final[id].pass).join(","));
  const rebuilt = applyEdits(input, A.sub.receipt.edits);
  ok(c, "the receipt's deletions re-applied to the original reproduce the output's sha256", sha256(rebuilt) === sha256(A.sub.html) && sha256(rebuilt) === A.sub.receipt.out.sha256);
  let i = 0; for (const ch of A.sub.html) { i = input.indexOf(ch, i); if (i < 0) break; i++; }
  ok(c, "the output is a subsequence of the input (no byte that is not the specimen's)", i >= 0);
  ok(c, "generated bytes = 0", A.sub.receipt.generatedBytes === 0);
  const saving = 1 - A.sub.html.length / input.length;
  ok(c, "at least 30% smaller", saving >= 0.3, `${input.length} -> ${A.sub.html.length} bytes (${(saving * 100).toFixed(1)}% smaller)`);
  return { bytesIn: input.length, bytesOut: A.sub.html.length, saving, receipt: { ...A.sub.receipt, edits: A.sub.receipt.edits.length + " deletions (see ledger)" }, finalObligations: Object.fromEntries(Object.entries(A.final).map(([k, v]) => [k, v])) };
});

await crit("T3", async (c) => {
  const extras = { "custom tip": 'id="custom"', "round-up": 'id="roundup"', "currency select": 'id="currency"', "history list": 'id="historyList"', "theme toggle": 'id="themeBtn"', "copy button": 'id="copyBtn"', "clear button": 'id="clearBtn"' };
  const remaining = Object.entries(extras).filter(([, k]) => A.sub.html.includes(k)).map(([n]) => n);
  ok(c, "history list, theme toggle and copy button are gone", !["history list", "theme toggle", "copy button"].some((n) => remaining.includes(n)), `remaining: ${remaining.join(", ") || "none"}`);
  return { remaining, removed: Object.keys(extras).filter((n) => !remaining.includes(n)) };
});

await crit("T4", async (c) => {
  const leaf = A.attribution.filter((a) => !A.attribution.some((x) => x.parent === a.id));
  const held = leaf.filter((a) => a.breaks.length > 0);
  const share = held.length / leaf.length;
  ok(c, "at least 90% of surviving leaf atoms hold up an obligation", share >= 0.9, `${held.length}/${leaf.length} (${(share * 100).toFixed(0)}%)`);
  return { leafAtoms: leaf.length, holdUp: held.length, loose: leaf.filter((a) => !a.breaks.length).map((a) => a.label), byHolon: Object.fromEntries(Object.entries(A.byHolon).map(([h, l]) => [h, l.filter((x) => x.leaf).length])) };
});

await crit("T5", async (c) => {
  const without = pool.filter((p) => p.name !== "tip-suite");
  B = await assemblePage(without, oracle, ledgerB);
  ok(c, "no specimen passes all (a void)", B.status === "void", B.status);
  ok(c, "the nearest is bill-splitter", B.nearest && B.nearest.name === "bill-splitter", B.nearest && `${B.nearest.name} ${B.nearest.passed}/11`);
  const names = B.def.voids.map((v) => v.holon).sort();
  ok(c, "the void names exactly tip-buttons, compute, display", JSON.stringify(names) === JSON.stringify(["compute", "display", "tip-buttons"]), names.join(", "));
  const nearestHtml = without.find((p) => p.name === B.nearest.name).html;
  for (const v of B.def.voids) {
    ok(c, `${v.holon}: lists suppliers, consumers and unmet obligations with what was observed`, v.unmet.length > 0 && v.unmet.every((u) => u.observed) && Array.isArray(v.suppliers) && Array.isArray(v.consumers), `${v.unmet.length} unmet, ${v.suppliers.length} suppliers, ${v.consumers.length} consumers`);
    ok(c, `${v.holon}: has a seam of at least one statement`, v.seam.length >= 1, `${v.seam.length} statements`);
    ok(c, `${v.holon}: every seam statement is found at its byte range`, v.seam.every((s) => nearestHtml.slice(s.start, s.end).replace(/\s+/g, " ").trim().slice(0, 160) === s.text));
  }
  return { nearest: B.nearest, def: B.def };
});

await crit("T6", async (c) => {
  const order = B.asks.map((a) => a.path[a.path.length - 1]);
  ok(c, "one ask per void, tip-buttons before compute before display", JSON.stringify(order) === JSON.stringify(["tip-buttons", "compute", "display"]), order.join(" -> "));
  const sizes = B.asks.map((a) => JSON.stringify(a).length);
  ok(c, "each ask is at most 2500 characters as JSON", sizes.every((s) => s <= 2500), sizes.join(", "));
  const holonIds = []; (function walk(n) { holonIds.push(n.id); (n.children || []).forEach(walk); })(TREE);
  const guard = makeGuard({ vocabulary: [...OBLIGATION_IDS, ...holonIds, "ask"] });   // exact whole-value matches only; see lib/guard.mjs
  const masked = []; let failed = null;
  for (const a of B.asks) {
    try { const g = await guard(a); masked.push({ ask: a.path.join("/"), viaRedactor: g.viaRedactor, passes: g.passes, stats: g.stats, changes: diffMasked(a, g.request), request: g.request }); }
    catch (e) { failed = e; masked.push({ ask: a.path.join("/"), notSent: !!e.notSent, error: e.message }); }
  }
  if (failed) { ok(c, "masked asks equal the originals (the door)", null, `the door failed closed: ${failed.message}`); }
  else {
    ok(c, "every ask went through the real redactor", masked.every((m) => m.viaRedactor === true));
    ok(c, "masking altered no field (no slot, holon or obligation id changed)", masked.every((m) => m.changes.length === 0), JSON.stringify(masked.flatMap((m) => m.changes).slice(0, 4)));
  }
  return { sizes, masked: masked.map((m) => ({ ...m, request: undefined })), asks: B.asks, guard: "values-only masking with an exact-match vocabulary exemption (run 2); run 1 masked the serialised JSON" };
});

await crit("T7", async (c) => {
  const f = path.join(OUT, "probe", "tip-suite.extracted.html");
  if (!fs.existsSync(f)) { ok(c, "extractor output present", null, "missing; run the khora screen.mjs probe"); return {}; }
  const r = await oracle.check(fs.readFileSync(f, "utf8"));
  const passed = OBLIGATION_IDS.filter((id) => r[id].pass);
  console.log(`   (reported, not graded) the screenshot extractor's page passes ${passed.length}/11: ${passed.join(", ")}`);
  return { passed, failed: OBLIGATION_IDS.filter((id) => !r[id].pass), detail: Object.fromEntries(OBLIGATION_IDS.map((id) => [id, r[id]])) };
});

await crit("T8", async () => {
  const st = A.sub.stats;
  console.log(`   (reported) atoms ${st.atoms}, oracle calls ${st.oracleCalls}, rounds ${st.rounds}, parse-rejected ${st.parseRejected}, wall ${((Date.now() - tA) / 1000).toFixed(0)} s (load-sensitive)`);
  return { ...st, wallMs: Date.now() - tA, browserLoads: oracle.loads };
});

// everything the viewer needs (a rerun replaces only the void and the masked asks)
const voidShow = () => ({ nearest: B.nearest, def: B.def, asks: B.asks, rows: B.rows.map((r) => ({ name: r.name, bytes: r.bytes, passed: r.passed, results: Object.fromEntries(OBLIGATION_IDS.map((id) => [id, { pass: r.results[id].pass, detail: r.results[id].detail }])) })), nearestHtml: pool.find((p) => p.name === B.nearest.name).html });
const showFull = () => ({
  ask: "single-file HTML tip calculator: bill input, 10%/15%/20% tip buttons, people input, live tip and per-person text, never negative",
  pool: A.rows.map((r) => ({ name: r.name, bytes: r.bytes, passed: r.passed, results: Object.fromEntries(OBLIGATION_IDS.map((id) => [id, { pass: r.results[id].pass, detail: r.results[id].detail }])) })),
  chosen: A.chosen, states: A.sub.states, finalHtml: A.sub.html, receipt: { ...A.sub.receipt, edits: A.sub.receipt.edits.map((e) => ({ start: e.start, end: e.end, bytes: e.end - e.start, preview: e.from.replace(/\s+/g, " ").trim().slice(0, 90) })) },
  ledger: ledgerA.events.filter((e) => e.kind === "cut" || e.kind === "kept").map((e) => ({ kind: e.kind, atom: e.kind === "cut" ? e.label : e.label, atomKind: e.atomKind || e.kind, what: e.kind === "cut" ? `${e.label}` : `${e.label} — ${e.why}`, round: e.round })),
  byHolon: A.byHolon, tree: statusTree(A.rows.find((r) => r.name === "tip-suite").results),
  void: voidShow(),
  masked: res.criteria.T6.evidence.masked,
});
res.show = RERUN ? { ...prev.show, void: voidShow(), masked: res.criteria.T6.evidence.masked } : showFull();
res.finishedAt = new Date().toISOString();
fs.writeFileSync(path.join(OUT, "pages-results.json"), JSON.stringify(res, null, 1));
await oracle.close();
console.log("\nSUMMARY");
for (const [id, v] of Object.entries(res.criteria)) console.log(`  ${id}  ${v.verdict}  (${v.checks.filter((x) => x.ok === true).length}/${v.checks.length})`);
console.log(`PAGES.md matches PAGES.sha256: ${res.pagesMatchesPrereg}`);
