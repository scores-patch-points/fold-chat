/** case: { answer, material:[{ref,source,text}] } -> rec shaped like the app's persisted grounding record. */
export function recordOf({ answer, material }, { agreement = null, k6 = true } = {}) {
  const mat = material.map((m) => ({ ref: m.ref, source: m.source || m.url, text: m.text }));
  const rec = G.turnRecord(answer, mat, { turn: 1 });
  const sents = splitS(answer).slice(0, 6);
  const checks = sents.map((s) => computeCheck(s, mat));
  rec.tape = [...material.map((m, i) => ({ kind: "quick", n: i + 1, of: material.length, p: { text: m.text.slice(0, 900), ref: m.ref, url: m.source || m.url } })), ...(k6 ? [{ kind: "check", k: 6, text: answer, sents, checks }] : [])];
  if (agreement === "auto") { const ag = P.agreementOf(answer, mat.map((m) => ({ text: m.text, url: m.source, ref: m.ref }))); rec.agreement = ag; } else if (agreement) rec.agreement = agreement;
  return rec;
}

/** The three rows under study, as the user would see them. */
export function rowsOf(rec) {
  const all = P.falsifiersOf(rec);
  const out = {};
  for (const r of all) {
    const st = [r.ground, r.figure, r.pattern].map((c) => c?.status);
    const shown = st.includes("failed") ? "failed" : (st.includes("gap") || st.includes("refused")) ? "flagged" : "clear";
    out[r.op] = { fig: r.status, shown, found: r.found, ground: r.ground.status, pattern: r.pattern.status, groundFound: r.ground.found, patternFound: r.pattern.found };
  }
  out._flagCount = all.filter((r) => { const st = [r.ground, r.figure, r.pattern].map((c) => c?.status); return !st.includes("failed") && (st.includes("gap") || st.includes("refused")); }).length;
  out._failCount = all.filter((r) => [r.ground, r.figure, r.pattern].some((c) => c?.status === "failed")).length;
  return out;
}
